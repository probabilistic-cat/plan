-- Schema
CREATE SCHEMA :"DB_SCHEMA";
ALTER SCHEMA :"DB_SCHEMA" OWNER TO :"DB_OWNER";

-- Schema privileges
GRANT USAGE, CREATE ON SCHEMA :"DB_SCHEMA"
    TO :"DB_USER_MIGRATION";
GRANT USAGE ON SCHEMA :"DB_SCHEMA"
    TO :"DB_USER_APP";

-- Future tables and sequences created by DB_USER_MIGRATION
ALTER DEFAULT PRIVILEGES
    FOR ROLE :"DB_USER_MIGRATION"
    IN SCHEMA :"DB_SCHEMA"
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO :"DB_USER_APP";
ALTER DEFAULT PRIVILEGES
    FOR ROLE :"DB_USER_MIGRATION"
    IN SCHEMA :"DB_SCHEMA"
    GRANT USAGE, SELECT, UPDATE ON SEQUENCES TO :"DB_USER_APP";

-- Search path
ALTER ROLE :"DB_USER_APP" IN DATABASE :"DB_NAME"
    SET search_path TO :"DB_SCHEMA";
ALTER ROLE :"DB_USER_MIGRATION" IN DATABASE :"DB_NAME"
    SET search_path TO :"DB_SCHEMA";

-- Delete default schema
DROP SCHEMA public CASCADE;
