-- Roles
CREATE ROLE :"DB_OWNER" NOLOGIN;
CREATE USER :"DB_USER_MIGRATION" WITH PASSWORD :'DB_USER_MIGRATION_PASSWORD';
CREATE USER :"DB_USER_APP" WITH PASSWORD :'DB_USER_APP_PASSWORD';

-- Database
CREATE DATABASE :"DB_NAME" OWNER :"DB_OWNER";

-- Connection privileges
GRANT CONNECT ON DATABASE :"DB_NAME" TO :"DB_USER_MIGRATION", :"DB_USER_APP";
